import fs from "fs";

const srcPath = "src/data/curriculum.ts";
let src = fs.readFileSync(srcPath, "utf8");

function setContent(id, newContent) {
  const idRegex = new RegExp('id: "' + id + '"');
  const idMatch = idRegex.exec(src);
  if (!idMatch) { console.error("Not found:", id); return false; }
  const topicStart = idMatch.index;
  const fromContent = src.indexOf("content:", topicStart);
  if (fromContent === -1) { console.error("No content for:", id); return false; }
  let qPos = fromContent + 8;
  while (qPos < src.length && src[qPos] === " ") qPos++;
  const restAfterContent = src.slice(qPos + 1);
  const fieldPatterns = [',\n            codeExample:', ',\n            tags:', ',\n            keyPoints:'];
  let earliestPos = -1;
  let earliestField = '';
  for (const fp of fieldPatterns) {
    const pos = restAfterContent.indexOf(fp);
    if (pos !== -1 && (earliestPos === -1 || pos < earliestPos)) { earliestPos = pos; earliestField = fp; }
  }
  if (earliestPos === -1) { console.error("Cannot find next field for:", id); return false; }
  const contentFieldEnd = qPos + 1 + earliestPos;
  const before = src.slice(0, fromContent);
  const after = src.slice(contentFieldEnd);
  const escaped = newContent.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\${/g, "\\${");
  src = before + "content: `" + escaped + "`" + after;
  console.log("Fixed:", id);
  return true;
}

