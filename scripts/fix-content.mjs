  "",
  "```javascript",
  "function a() { b(); }",
  "function b() { c(); }",
  "function c() { console.log('hello'); }",
  "a();",
  "// Stack: [global] -> [a] -> [b] -> [c] -> [b] -> [a] -> [global]",
  "// Execution is strictly sequential through this chain",
  "```",
  "",
  "This single-threaded model has a profound consequence: **long-running synchronous operations freeze the entire application**. A 500ms synchronous loop in the browser freezes all UI updates, user input, and network event processing. In Node.js, it blocks all incoming request processing. The only way to avoid this is to never block the stack for more than a few milliseconds at a time.",
  "",
  "## The Event Loop: What It Actually Is",
  "",
  "The event loop is not part of the JavaScript language — it is provided by the **runtime environment** (the browser or Node.js). It is a continuous loop that checks whether there are pending tasks to execute, and if so, runs them one at a time on the call stack. The loop itself has a well-defined order of operations specified by the HTML standard:",
  "",
  "```",
  "While (true):",
  "  1. Pick the oldest macrotask from the macrotask queue",
  "  2. Execute it (run its callbacks on the stack until empty)",
  "  3. Drain the ENTIRE microtask queue (execute all microtasks until empty)",
  "  4. Check if rendering is needed (update style, layout, paint)",
  "  (Repeat)",
  "```",
  "",
  "## Macrotasks vs Microtasks",
  "",
  "Understanding the two types of tasks — and their prioritization — is the most important part of the event loop model.",
  "",
  "### Macrotasks (Tasks)",
  "",
  "Macrotasks are the basic unit of work in the event loop. Each iteration of the loop processes exactly one macrotask. Sources of macrotasks include:",
  "",
  "- Parsing a chunk of HTML",
  "- Firing a DOM event (click, keydown, mousemove)",
  "- `setTimeout()` and `setInterval()` callbacks",
  "- I/O completion callbacks (fetch, file reads, sockets)",
  "- `requestAnimationFrame()` callbacks (actually processed in the render step, but often grouped conceptually)",
  "",
  "### Microtasks",
  "",
  "Microtasks are higher-priority work that must be completed before the event loop can proceed to the next macrotask. The microtask queue is drained **completely** — if a microtask enqueues another microtask, the new one is processed immediately, before the next macrotask or render step. Sources of microtasks include:",
  "",
