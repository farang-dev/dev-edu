  "}",
  "",
  "// GOOD: requestAnimationFrame — synchronized with paint cycle",
  "function animate() {",
  "  element.style.transform = `translateX(${x++}px)`;",
  "  requestAnimationFrame(animate);  // fires exactly once before each paint",
  "}",
  "```",
  "",
  "## CTO-Level Takeaways",
  "",
  "1. **Never block the stack.** Synchronous loops, heavy computations, or synchronous I/O in the main thread destroys responsiveness. Use Web Workers or offload to the backend.",
  "2. **Use microtasks for synchronous-looking async code.** Promises and `queueMicrotask` are the correct tools for sequencing dependent operations without frame delays.",
