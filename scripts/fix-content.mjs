  "3. Performing layout (if any layout properties changed)",
  "4. Painting layers",
  "5. Compositing layers on the GPU",
  "",
  "`requestAnimationFrame` is **not** a macrotask or microtask — it is queued separately and processed during the render step. This makes it the ideal scheduling primitive for visual updates:",
  "",
  "```javascript",
