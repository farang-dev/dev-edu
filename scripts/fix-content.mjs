  "}",
  "loop();",
  "// No rendering ever happens again",
  "```",
  "",
  "2. **Promise resolution order:** Since `.then()` callbacks are microtasks, a resolved promise's callbacks always run before any queued `setTimeout` callback, even if the promise was resolved before the timeout was created.",
