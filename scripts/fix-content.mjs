  "",
  "## requestAnimationFrame and the Render Step",
  "",
  "After draining microtasks, the browser checks if a render is needed. Renders happen approximately every 16.6ms (60fps), but the browser may skip frames if the page is not changing or if the event loop is busy.",
  "",
  "The render step includes:",
